const assert=require('node:assert/strict');
const S=require('../autocaption/web_static/shortcuts.js');
assert.deepEqual(S.action({code:'KeyZ',key:'ז',ctrlKey:true}),{kind:'undo'});
assert.deepEqual(S.action({code:'KeyY',key:'ט',ctrlKey:true}),{kind:'redo'});
assert.deepEqual(S.action({code:'KeyZ',metaKey:true,shiftKey:true}),{kind:'redo'});
for(const flag of ['editable','modal','composing'])assert.equal(S.action({code:'KeyZ',ctrlKey:true,[flag]:true}),null);
assert.equal(S.action({code:'KeyZ',ctrlKey:true,altKey:true}),null);
assert.deepEqual(S.action({key:'ArrowLeft'}),{kind:'seek',delta:-.5});
assert.deepEqual(S.action({key:'ArrowRight',altKey:true}),{kind:'seek',delta:.01});
assert.deepEqual(S.action({key:'ArrowLeft',shiftKey:true}),{kind:'seek',delta:-5});
assert.deepEqual(S.action({code:'KeyL',key:'ך'}),{kind:'seek',delta:5});
assert.deepEqual(S.action({code:'KeyK',key:'ל'}),{kind:'play'});
assert.deepEqual(S.action({key:'PageDown'}),{kind:'word',direction:1});
assert.equal(S.action({key:'ArrowRight',ctrlKey:true}),null);
const word=S.mark({before:[1],after:[2]}),style=S.mark({font_size:110});
assert.ok(style.editOrder>word.editOrder);
assert.deepEqual({...style},{font_size:110});
assert.equal(JSON.stringify(style),'{"font_size":110}');
S.mark(word);assert.ok(word.editOrder>style.editOrder);
console.log('Hebrew keyboard shortcuts, input guards, steps and cross-editor history order passed.');
